"""
API Calling the retry mechanism
For processing LLM etc. External API Call of retry logic
"""

import time
import random
import functools
from typing import Callable, Any, Optional, Type, Tuple
from ..utils.logger import get_logger

logger = get_logger('Veyronix.retry')


def retry_with_backoff(
    max_retries: int = 3,
    initial_delay: float = 1.0,
    max_delay: float = 30.0,
    backoff_factor: float = 2.0,
    jitter: bool = True,
    exceptions: Tuple[Type[Exception], ...] = (Exception,),
    on_retry: Optional[Callable[[Exception, int], None]] = None
):
    """
    Decorator with finger count retreat of retry
    
    Args:
        max_retries: maximum retry times count
        initial_delay: Initial delay（seconds）
        max_delay: maximum delay（seconds）
        backoff_factor: Retreat factor
        jitter: Whether to add random jitter
        exceptions: need retry of exception type
        on_retry: retry of callback count (exception, retry_count)
    
    Usage:
        @retry_with_backoff(max_retries=3)
        def call_llm_api():
            ...
    """
    def decorator(func: Callable) -> Callable:
        @functools.wraps(func)
        def wrapper(*args, **kwargs) -> Any:
            last_exception = None
            delay = initial_delay
            
            for attempt in range(max_retries + 1):
                try:
                    return func(*args, **kwargs)
                    
                except exceptions as e:
                    last_exception = e
                    
                    if attempt == max_retries:
                        logger.error(f"Letter count {func.__name__} in {max_retries} times retry still failed: {str(e)}")
                        raise
                    
                    # calculate delay
                    current_delay = min(delay, max_delay)
                    if jitter:
                        current_delay = current_delay * (0.5 + random.random())
                    
                    logger.warning(
                        f"Letter count {func.__name__} No. {attempt + 1} times attempt failed: {str(e)}, "
                        f"{current_delay:.1f}seconds after retry..."
                    )
                    
                    if on_retry:
                        on_retry(e, attempt + 1)
                    
                    time.sleep(current_delay)
                    delay *= backoff_factor
            
            raise last_exception
        
        return wrapper
    return decorator


